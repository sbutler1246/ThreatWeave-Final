from typing import Protocol
from schemas import Chunk, ExtractionBatch, EntityCandidate, ResolutionResult, QueryRequest, EvidenceBundle, AnswerResponse

class Extractor(Protocol):
    def extract(self, chunk: Chunk) -> ExtractionBatch: ...
class Resolver(Protocol):
    def resolve(self, entity: EntityCandidate) -> ResolutionResult: ...
class Retriever(Protocol):
    def retrieve(self, request: QueryRequest) -> EvidenceBundle: ...
class Generator(Protocol):
    def generate(self, request: QueryRequest, bundle: EvidenceBundle) -> AnswerResponse: ...
class QueryEngine(Protocol):
    def query(self, request: QueryRequest) -> AnswerResponse: ...
